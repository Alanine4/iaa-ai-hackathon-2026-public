# ---- 5. numbers for the conclusion (interpretation text is added by hand below the data lines)
c = ["## 5. Conclusion", "", "Numbers (generated):", ""]
for line in LINES:
    for scheme in ["time", "group"]:
        n = conc[(line, scheme, "new")]
        rn = conc[(line, scheme, "renewal")]
        c.append(f"- {line}, {scheme}: blend pred/actual on new business = {n['blend_P2S05']:.3f} "
                 f"({n['claims']} claims, {n['rows']} rows) vs renewal {rn['blend_P2S05']:.3f} "
                 f"({rn['claims']} claims).")
c.append("")
c.append("- Training developed pure-premium ratio new/renewal: " + "; ".join(
    f"{l} {conc[(l, 'exp_ratio')]:.3f} (new share of exposure {conc[(l, 'exp_share')]:.3f})" for l in LINES) + ".")
tt = conc[("contents", "test")]
c.append("- Contents test predictions, new/renewal ratio of mean per exposure-year: " + "; ".join(
    f"{k.replace(' per exp-yr', '')} {tt.iloc[2][k]:.3f}" for k in tt.columns if k.endswith("per exp-yr")) + ".")
c.append("")
c.append(INTERPRETATION)
md += c
(ROOT / "docs/part2_new_business_check.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("written")
