"""Read-only diagnostic for C042 review: do the pooled emerging-market models
mis-state the level of NEW BUSINESS rows?

The 2025 test set is mostly new business while the emerging training rows are
only a small share new business, so a segment bias would barely show in
validation but would matter on the test. This script trains nothing; it only
reads existing policy / target / OOF / prediction files and writes
docs/part2_new_business_check.md.

Run: .venv\\Scripts\\python.exe -I scripts/part2_new_business_check.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/iaa-ai-assisted-hackathon-2026-part-2/emerging"
OUT = ROOT / "output/emerging"
LINES = ["motor", "buildings", "contents"]
MODELS = ["glm", "lgbm", "xgb", "cat"]

# Current submission P2-S05 recipes: (run directory, weights).
RECIPE = {
    "motor": ("pooled_w0.3", {"glm": .25, "lgbm": .25, "xgb": .25, "cat": .25}),
    "buildings": ("pooled_w1", {"cat": .95, "lgbm": .05}),
    "contents": ("pooled_w0.3", {"glm": .55, "xgb": .25, "lgbm": .20}),
}


def read(path):
    return pd.read_parquet(path)


def seg_name(b):
    return "new" if b else "renewal"


def fmt(v):
    if isinstance(v, (float, np.floating)):
        return f"{v:,.3f}"
    if isinstance(v, (int, np.integer)):
        return f"{v:,}"
    return str(v)


def table(df):
    """Markdown table from a DataFrame."""
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt(r[c]) for c in cols) + " |")
    return "\n".join(lines)


md = ["# Part 2 emerging market: new-business level check",
      "",
      "Diagnostic for C042 review. Read-only; no model was trained. Generated by "
      "`scripts/part2_new_business_check.py`.",
      "",
      "Conventions: developed pure premium = sum(`claim_cost_ult`) / sum(`exposure`) "
      "(`claim_cost_ult` from `output/emerging/target_<line>.parquet`). In the OOF tables "
      "`actual` is the reported (undeveloped) cost and predictions already include "
      "exposure x completeness x load, so pred/actual is comparable within a scheme; "
      "a ratio well below 1 on new business means under-prediction. Claim counts are "
      "`claim_count` from the target table, summed over the OOF rows in the segment. "
      "Scheme `time` = train 2023, validate 2024; `group` = grouped 5-fold over all rows.",
      ""]

conc = {}  # numbers reused in the conclusion

for line in LINES:
    pol = read(DATA / f"policies_{line}.parquet")[["row_id", "period_start", "exposure", "new_business"]].copy()
    tgt = read(OUT / f"target_{line}.parquet").drop(columns=["exposure"])
    d = pol.merge(tgt, on="row_id", how="left", validate="1:1")
    assert d["claim_cost_ult"].notna().all()
    d["year"] = pd.to_datetime(d["period_start"]).dt.year.astype(str)
    d["seg"] = d["new_business"].map(seg_name)
    md += [f"## {line}", "", "### 1. Training experience by segment", ""]

    def exp_table(keys):
        g = d.groupby(keys).agg(rows=("row_id", "size"), exposure=("exposure", "sum"),
                                claims=("claim_count", "sum"), ult=("claim_cost_ult", "sum")).reset_index()
        g["pure_premium_ult"] = g["ult"] / g["exposure"]
        return g.drop(columns="ult")

    g = exp_table(["seg"])
    g["exposure_share"] = g["exposure"] / d["exposure"].sum()
    g["row_share"] = g["rows"] / len(d)
    g = g.set_index("seg").loc[["new", "renewal"]].reset_index()
    pp = g.set_index("seg")["pure_premium_ult"]
    conc[(line, "exp_ratio")] = pp["new"] / pp["renewal"]
    conc[(line, "exp_share")] = g.set_index("seg").loc["new", "exposure_share"]
    md += [table(g), "", f"Pure premium ratio new/renewal (all years): **{pp['new'] / pp['renewal']:.3f}**", ""]
    gy = exp_table(["year", "seg"])
    gy["pp_ratio_new_over_renewal"] = gy.groupby("year")["pure_premium_ult"].transform(
        lambda s: s.iloc[0] / s.iloc[1] if len(s) == 2 else np.nan)  # rows sorted new, renewal
    md += ["By accident year (year of `period_start`):", "", table(gy), ""]

    # --- 2. OOF calibration
    run, w = RECIPE[line]
    oof = read(OUT / run / f"oof_{line}.parquet")
    oof["blend_P2S05"] = sum(oof[m] * wt for m, wt in w.items())
    oof = oof.merge(d[["row_id", "seg", "claim_count"]], on="row_id", how="left", validate="m:1")
    assert oof["seg"].notna().all(), "OOF rows not found in emerging policies"
    preds = ["blend_P2S05"] + MODELS
    if line == "contents":
        gx = read(OUT / "pooled_w0.3_glmx" / "oof_contents.parquet")[["row_id", "scheme", "fold", "glm"]]
        gx = gx.rename(columns={"glm": "glm_interaction"})
        oof = oof.merge(gx, on=["row_id", "scheme", "fold"], how="left", validate="1:1")
        assert oof["glm_interaction"].notna().all()
        preds.append("glm_interaction")
    md += [f"### 2{'+3' if line == 'contents' else ''}. OOF calibration, sum(pred)/sum(actual) "
           f"(run `{run}`; blend weights {w}"
           + ("; `glm_interaction` = `pooled_w0.3_glmx` GLM, `glm` = plain GLM" if line == "contents" else "")
           + ")", ""]
    rows = []
    for scheme in ["time", "group"]:
        o = oof[oof["scheme"] == scheme]
        for seg in ["new", "renewal"]:
            s = o[o["seg"] == seg]
            r = {"scheme": scheme, "segment": seg, "rows": len(s), "claims": int(s["claim_count"].sum()),
                 "actual_sum": round(s["actual"].sum())}
            for p in preds:
                r[p] = s[p].sum() / s["actual"].sum()
            rows.append(r)
            conc[(line, scheme, seg)] = r
    cal = pd.DataFrame(rows)
    md += [table(cal), "",
           "Relative calibration (ratio_new / ratio_renewal; 1 = no segment bias):", ""]
    rel = []
    for scheme in ["time", "group"]:
        a = cal[(cal.scheme == scheme) & (cal.segment == "new")].iloc[0]
        b = cal[(cal.scheme == scheme) & (cal.segment == "renewal")].iloc[0]
        rel.append({"scheme": scheme, **{p: a[p] / b[p] for p in preds}})
    md += [table(pd.DataFrame(rel)), ""]

    # --- 4. test set
    te = read(DATA / f"test_{line}.parquet")[["row_id", "exposure", "new_business"]]
    te["seg"] = te["new_business"].map(seg_name)
    for m in w:
        p = read(OUT / run / f"pred_{line}_{m}.parquet")[["row_id", "prediction"]]
        te = te.merge(p.rename(columns={"prediction": m}), on="row_id", how="left", validate="1:1")
        assert te[m].notna().all()
    te["blend_P2S05"] = sum(te[m] * wt for m, wt in w.items())
    tp = ["blend_P2S05"]
    if line == "contents":
        for name, path in [("glm_plain", OUT / run / "pred_contents_glm.parquet"),
                           ("glm_interaction", OUT / "pooled_w0.3_glmx" / "pred_contents_glm.parquet")]:
            p = read(path)[["row_id", "prediction"]]
            te = te.merge(p.rename(columns={"prediction": name}), on="row_id", how="left", validate="1:1")
            assert te[name].notna().all()
        tp += ["glm_plain", "glm_interaction"]
    rows = []
    for seg in ["new", "renewal"]:
        s = te[te["seg"] == seg]
        r = {"segment": seg, "rows": len(s), "exposure": s["exposure"].sum(),
             "exposure_share": s["exposure"].sum() / te["exposure"].sum()}
        for p in tp:
            r[p + " per exp-yr"] = s[p].sum() / s["exposure"].sum()
        rows.append(r)
    tt = pd.DataFrame(rows)
    rr = {"segment": "ratio new/renewal", "rows": "", "exposure": "", "exposure_share": ""}
    for p in tp:
        rr[p + " per exp-yr"] = tt.iloc[0][p + " per exp-yr"] / tt.iloc[1][p + " per exp-yr"]
    tt = pd.concat([tt, pd.DataFrame([rr])], ignore_index=True)
    md += ["### 4. Test set (2025)", "",
           f"New-business share of test rows: {(te['seg'] == 'new').mean():.3f}; of test exposure: "
           f"{tt.iloc[0]['exposure_share']:.3f}. Mean prediction per exposure-year = "
           "sum(raw test prediction) / sum(exposure).", "", table(tt), ""]
    conc[(line, "test")] = tt

